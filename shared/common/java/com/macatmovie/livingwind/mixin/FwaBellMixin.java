package com.macatmovie.livingwind.mixin;

import com.macatmovie.livingwind.client.compat.FwaAnimationAccess;
import com.macatmovie.livingwind.client.compat.FwaWindMotion;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.level.block.state.properties.BellAttachType;
import com.macatmovie.livingwind.client.ClientWindState;
import com.macatmovie.livingwind.wind.WindMath;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Pseudo;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.Unique;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/** Adjusts ONLY FWA's idle bell wobble, never the vanilla bell ringing animation. */
@Pseudo
@Mixin(targets = "fr.madu59.fwa.anims.BellAnimation", remap = false)
public abstract class FwaBellMixin {
    @Shadow(remap = false) @Final private Direction facing;
    @Shadow(remap = false) @Final private BellAttachType attachment;

    @Inject(method = "animateIdle(F)F", at = @At("RETURN"), cancellable = true, remap = false, require = 0)
    private void livingwind$applyBellWind(float time, CallbackInfoReturnable<Float> cir) {
        BlockPos pos = ((FwaAnimationAccess)(Object)this).livingwind$getPosition();
        // FWA maps its signed idle 'rot' onto xRot or zRot according to both facing
        // and wall attachment. Project the actual downwind vector onto the bell-tip
        // displacement generated by a positive rot, so it swings AWAY from the source.
        float wx = WindMath.windX(1.0f, ClientWindState.directionDegrees());
        float wz = WindMath.windZ(1.0f, ClientWindState.directionDegrees());
        boolean wall = attachment == BellAttachType.SINGLE_WALL;
        float projection;
        switch (facing) {
            case NORTH -> projection = wall ? -wx : wz;
            case SOUTH -> projection = wall ? wx : -wz;
            case EAST -> projection = wall ? -wz : wx;
            case WEST -> projection = wall ? wz : -wx;
            default -> projection = 0.0f;
        }
        FwaWindMotion.Smoother smoother = FwaWindMotion.smootherFor(pos, FwaWindMotion.ObjectType.BELL);
        smoother.begin(new FwaWindMotion.Angles(cir.getReturnValueF(), 0.0f, 0.0f));
        float modified = FwaWindMotion.bellIdle(pos, cir.getReturnValueF(), projection, smoother);
        cir.setReturnValue(smoother.update(
            new FwaWindMotion.Angles(modified, 0.0f, 0.0f)).x());
    }
}
